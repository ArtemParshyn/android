// Вывод чисел от 1 до 5
for (i in 1..5) {
    println(i)
}

// ----

1
2
3
4
5

// ----

// Вывод чётных чисел от 0 до 10
for (i in 0..10 step 2) {
    println(i)
}

// ----

0
2
4
6
8
10

// ----

// Обратный отсчёт от 5 до 1
for (i in 5 downTo 1) {
    println(i)
}

// ----

5
4
3
2
1

// ----

// Вывод чисел от 1 до 4 (без 5)
for (i in 1 until 5) {
    println(i)
}

// ----

1
2
3
4
